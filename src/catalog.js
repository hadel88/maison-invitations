export const localeMap = { en: "en-GB", de: "de-DE", fr: "fr-FR" };
export function dateLabel(
  date,
  lang = "en",
  opts = { day: "numeric", month: "long", year: "numeric" },
) {
  try {
    return new Intl.DateTimeFormat(localeMap[lang] || "en-GB", {
      ...opts,
      timeZone: "UTC",
    }).format(new Date(date + "T12:00:00Z"));
  } catch {
    return date;
  }
}
